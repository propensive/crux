package crux

import mill.*
import mill.javalib.CoursierModule

// Mixed into a module that compiles against pinned releases: its resolution consults the pinned
// repositories before the defaults.
//
//     trait Project extends ScalaModule, CruxDeps:
//       def crux = deps
//       def mvnDeps = Seq(crux.dep("soundness", "rudiments-core")())
//
// `repositoriesTask` rather than `repositories`, because the gate `GitHubRepository` applies has
// no repository-string form.
trait CruxDeps extends CoursierModule:
  def crux: CruxModule

  override def repositoriesTask: Task[Seq[coursier.Repository]] = Task.Anon:
    crux.coursierRepositories() ++ super.repositoriesTask()
